"""Build publications.qmd directly from a BibTeX file.

Usage: python3 build_publications.py [path/to/ketcheson.bib]

The HTML for each entry is produced by the existing generator
~/Research/Software/tex2_rst_html/bibtex2htmldiv.py (imported, not modified).
This script adds, before calling it:
  - LaTeX accents in text fields are converted to Unicode (via latexcodec).
  - Articles whose journal is "arXiv preprint ..." are listed under
    "Submitted preprints" instead of "Refereed Journal Articles".
  - Topic tags and title fixes from publication_tags.yml are merged in.
and after:
  - Links to files on davidketcheson.info become root-relative, and those
    files are copied from the Jekyll site's assets/ into this project.
  - The newest preprints are written to _recent_preprints.qmd, which
    index.qmd includes.
  - Paper images (<citekey>.png in PAPER_IMAGES) are copied into
    assets/paper_images/.
  - Each listed paper gets a supplementary page papers/<citekey>/; the
    entry's title and image link to it, and its links line gets "More
    information" and reproducibility-repository links.  See paper_pages.py.

The search box and filter buttons are implemented in publications.js.
Anything unexpected raises an error.
"""
