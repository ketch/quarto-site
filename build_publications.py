import paper_pages

HERE = Path(__file__).resolve().parent
JEKYLL_ROOT = Path.home() / "Research/Projects/labnotebook"  # the old Jekyll site
DEFAULT_BIB = Path.home() / "Library/CloudStorage/Dropbox/ketcheson.bib"
GENERATOR_DIR = Path.home() / "Research/Software/tex2_rst_html"
PAPER_IMAGES = Path.home() / "Library/CloudStorage/Box-Box/My Papers/paper_images"
TAGS_FILE = HERE / "publication_tags.yml"
DEST = HERE / "publications.qmd"

FILTER_TAGS = ["time-integration", "periodic-media", "hyperbolic", "ssp", "runge-kutta",
               "epidemiology"]
FILTER_LABELS = ["Time integration", "Waves in periodic media", "Hyperbolic PDEs",
                 "Strong stability preservation", "Runge-Kutta methods", "Epidemiology"]
# Each keyword becomes one CSS class, with spaces turned into hyphens
# ("time integration" -> "time-integration").  Keywords listed here also add
# the filter tags shown, for .bib spellings that differ from the tag names.
KEYWORD_FILTERS = {
    "hyperbolic pdes": ["hyperbolic"],
    "runge-kutta methods": ["runge-kutta"],
    "optimized explicit runge-kutta": ["runge-kutta"],
    "runge-kutta time-integration": ["runge-kutta", "time-integration"],
    "runge-kutta time-integration multi-rate": ["runge-kutta", "time-integration"],
    "strong stability preservation": ["ssp"],
    "strong stability preserving": ["ssp"],
}
TEXT_FIELDS = ["title", "journal", "booktitle", "school", "annote", "institution"]
SELF_LINK_RE = re.compile(r'(src|href)="https?://(?:www\.)?davidketcheson\.info/([^"]+)"')
LOCAL_IMG_RE = re.compile(r'src="/(assets/paper_images/[^"]+)"')


def header() -> str:
    buttons = "\n".join(
        f'<button class="pub-filter" data-filter="{t}">{label}</button>'
        for t, label in zip(FILTER_TAGS, FILTER_LABELS))
    return f"""\
---
title: Publications
page-layout: full
toc: false
include-after-body:
  text: '<script src="/publications.js"></script>'
---

<!-- Generated by build_publications.py; do not edit by hand. -->

<div class="pub-controls">
<input type="search" id="pub-search" placeholder="Search by title or author" aria-label="Search publications">
<div class="pub-filters" role="group" aria-label="Filter by topic">
<button class="pub-filter active" data-filter="all">All</button>
{buttons}
</div>
<p id="pub-count"></p>
</div>

"""


def decode_latex(s: str, where: str) -> str:
    out = codecs.decode(s, "ulatex+utf8")
    leftover = out.replace("{", "").replace("}", "")
    if "\\" in leftover or "$" in leftover:
        raise ValueError(f"LaTeX left after decoding {where}: {out!r} "
                         "(fix the .bib entry or add a title_override)")
    return out


ENTRY_RE = re.compile(r'<div id="pub" class="pub filterable ([^"]*)">\n(.*?)\n</div>\n', re.S)
# Hosts whose links in the generated list were checked (Nov 2026) to give the
# same response over https as over http; their http:// links become https://.
HTTPS_HOSTS = ["arxiv.org", "bitbucket.org", "doi.wiley.com", "dx.doi.org", "github.com",
               "imajna.oxfordjournals.org", "linkinghub.elsevier.com",
               "numerics.kaust.edu.sa", "www.amazon.com", "www.oulu.fi"]
HTTPS_RE = re.compile(r'(href|src)="http://(' + "|".join(map(re.escape, HTTPS_HOSTS)) + r')/')
TAG_CLASSES = {"name": "pub-title", "authors": "pub-authors",
               "journal": "pub-journal", "links": "pub-links"}


def clean_html(body: str) -> str:
    """Turn the generator's HTML into valid HTML that looks the same.

    - Drops the duplicate id="pub" on every entry.
    - Replaces the made-up <name>, <authors>, <journal>, <links> elements
      with <span class="pub-...">.  (Unknown elements are inline, as spans are.)
    - Replaces the obsolete align="right" on images (styles.css floats them)
      and gives each image the paper title as alt text.
    - Removes the leading and trailing "|" from the links line.
    - Changes http:// to https:// for the hosts in HTTPS_HOSTS.
    """
    n_entries = body.count('<div id="pub"')

    def entry(m):
        classes = " ".join(m.group(1).split())
        html_ = m.group(2)
        title = re.search(r"<name>(.*?)</name>", html_, re.S)
        if not title:
            raise ValueError(f"Publication entry without a title:\n{html_}")
        alt = html.escape(html.unescape(" ".join(title.group(1).split())), quote=True)
        html_, n_img = re.subn(r'<img src="([^"]+)" align="right" />',
                               rf'<img src="\1" alt="{alt}" />', html_)
        if n_img != html_.count("<img"):
            raise ValueError(f"Unexpected <img> markup:\n{html_}")

        def links(lm):
            parts = [s.strip() for s in lm.group(1).split("|")]
            return "<links>" + " | ".join(s for s in parts if s) + "</links>"
        html_ = re.sub(r"<links>(.*?)</links>", links, html_, flags=re.S)
        for tag, cls in TAG_CLASSES.items():
            html_ = re.sub(rf"<{tag}>\s*(.*?)\s*</{tag}>",
                           rf'<span class="{cls}">\1</span>', html_, flags=re.S)
        return f'<div class="pub filterable {classes}">\n{html_}\n</div>\n'

    body = HTTPS_RE.sub(r'\1="https://\2/', body)
    body, n = ENTRY_RE.subn(entry, body)
    if n != n_entries:
        raise ValueError(f"Cleaned {n} of {n_entries} publication entries")
    leftover = re.search(r"</?(name|authors|journal|links)>|id=\"pub\"|align=", body)
    if leftover:
        raise ValueError(f"Unconverted markup left: {leftover.group(0)!r}")
    return body


N_RECENT_PREPRINTS = 5
RECENT_DEST = HERE / "_recent_preprints.qmd"   # included by index.qmd


def recent_preprints(body: str) -> str:
    """Compact list of the newest preprints (by arXiv number) for the home page."""
    m = re.search(r"<h2>Submitted preprints</h2>\n(.*?)(?=<h2>|\Z)", body, re.S)
    if not m:
        raise ValueError("No 'Submitted preprints' section in the publication list")
    items = []
    for entry in re.findall(r'<div class="pub filterable[^"]*">\n(.*?)\n</div>', m.group(1), re.S):
        title = re.search(r'<a href="([^"]+)"><span class="pub-title">(.*?)</span>', entry, re.S)
        authors = re.search(r'<span class="pub-authors">(.*?)</span>', entry, re.S)
        arxiv = re.search(r'href="https://arxiv\.org/abs/(\d{4}\.\d{4,5})"', entry)
        if not (title and authors and arxiv):
            raise ValueError(f"Preprint entry missing title link, authors, or arXiv link:\n{entry}")
        items.append((arxiv.group(1), title.group(1), title.group(2), " ".join(authors.group(1).split())))
    if not items:
        raise ValueError("The 'Submitted preprints' section has no entries")
    items.sort(reverse=True)
    lis = "\n".join(
        f'<li><a href="{url}">{t}</a><br>\n<span class="pub-authors">{a}</span>, '
        f'<span class="pub-journal">arXiv:{num}</span></li>'
        for num, url, t, a in items[:N_RECENT_PREPRINTS])
    return ("<!-- Generated by build_publications.py; do not edit by hand. -->\n\n"
            '```{=html}\n<ul class="recent-preprints">\n' + lis + "\n</ul>\n```\n")


def gen_links() -> dict:
    """The extra links per paper from the Jekyll site's paperlinks.txt (also read by the generator)."""
    return ast.literal_eval((JEKYLL_ROOT / "assets/paperlinks.txt").read_text())


def load_generator():
    sys.path.insert(0, str(GENERATOR_DIR))
    import bibtex2htmldiv as gen
    gen.img_path = str(PAPER_IMAGES) + "/"
    gen.img_dest = "/assets/paper_images/"
    gen.paperlinks_path = str(JEKYLL_ROOT / "assets/paperlinks.txt")
    return gen


def main(bibfile: Path):
    if not PAPER_IMAGES.is_dir():
        raise FileNotFoundError(f"Paper image folder not found: {PAPER_IMAGES}")
    extra = yaml.safe_load(TAGS_FILE.read_text())
    tags = extra.get("tags") or {}
    overrides = extra.get("title_overrides") or {}

    gen = load_generator()
    with contextlib.redirect_stdout(io.StringIO()):  # generator prints progress
        pubs = gen.parsefile(str(bibfile))
    keys = {p["pid"] for p in pubs}
    for name, table in (("tags", tags), ("title_overrides", overrides)):
        unknown = set(table) - keys
        if unknown:
            raise KeyError(f"{TAGS_FILE.name} {name} has keys not in {bibfile.name}: {unknown}")
    for key, tlist in tags.items():
        bad = set(tlist or []) - set(FILTER_TAGS)
        if bad:
            raise ValueError(f"Unknown tags for {key}: {bad}")

    by_pid = {p["pid"]: p for p in pubs}
    for key, text in (extra.get("abstract_overrides") or {}).items():
        if key not in by_pid:
            raise KeyError(f"{TAGS_FILE.name} abstract_overrides has a key not in {bibfile.name}: {key}")
        by_pid[key]["abstract"] = text

    n_preprint = 0
    for p in pubs:
        key = p["pid"]
        if key in overrides:
            p["title"] = overrides[key]
        for field in TEXT_FIELDS:
            if field in p:
                p[field] = decode_latex(p[field], f"{key}.{field}")
        p["author"] = [decode_latex(a, f"{key}.author") for a in p["author"]]
        if "`" in p["title"]:  # Markdown code marks, e.g. `NodePy`; shown raw in HTML
            p["title"] = p["title"].replace("`", "")
        if p["reference_type"] == "article" and p.get("journal", "").lower().startswith("arxiv"):
            p["reference_type"] = "unpublished"
            n_preprint += 1
        # For a preprint, an arXiv DOI would give a "Published version" link
        # that is the same paper as the "arXiv version" link.
        if p["reference_type"] == "unpublished" and \
                p.get("doi", "").lower().startswith("10.48550/arxiv"):
            if "arxivid" not in p:
                raise ValueError(f"{key}: arXiv DOI but no arxivid field")
            del p["doi"]
        keywords = [k.strip().lower() for k in re.split(r"[,;]", p.get("keywords", ""))
                    if k.strip()] + (tags.get(key) or [])
        classes = []
        for k in keywords:
            classes.append(re.sub(r"\s+", "-", k))
            classes += KEYWORD_FILTERS.get(k, [])
        p["keywords"] = ", ".join(dict.fromkeys(classes))
        p["authors_list"] = list(p["author"])  # writebib turns p["author"] into a string

    keys = paper_pages.listed_keys(gen, pubs)
    by_key = {p["pid"]: p for p in pubs}
    repos = {k: v["Reproducibility repository"] for k, v in gen_links().items()
             if k in by_key and "Reproducibility repository" in v}
    hidden_repos = {}   # paperlinks.txt repositories hidden by a null in publication_tags.yml
    for k, url in (extra.get("repos") or {}).items():
        if k not in by_key:
            raise KeyError(f"{TAGS_FILE.name} repos has a key not in {bibfile.name}: {k}")
        if url is None:
            if k not in repos:
                raise KeyError(f"{TAGS_FILE.name} repos: {k} is null but has no repository to hide")
            hidden_repos[k] = repos.pop(k)
            continue
        if k in repos and repos[k] != url:
            raise ValueError(f"{k}: repository {url} in {TAGS_FILE.name} but {repos[k]} in paperlinks.txt")
        repos[k] = url
    abstracts = paper_pages.update_abstract_cache(pubs, keys)

    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "bib.html"
        with contextlib.redirect_stdout(io.StringIO()):
            gen.writebib(pubs, str(out))
        body = out.read_text()

    missing = []

    def relink(m):
        attr, path = m.groups()
        source = JEKYLL_ROOT / path
        if not source.is_file():
            missing.append(path)
            return m.group(0)
        dest = HERE / path
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, dest)
        return f'{attr}="/{path}"'

    body = SELF_LINK_RE.sub(relink, body)
    if missing:
        raise FileNotFoundError("Linked files not in the Jekyll repo:\n  "
                                + "\n  ".join(sorted(set(missing))))

    body = clean_html(body)
    for doi, label in (extra.get("doi_labels") or {}).items():
        link = f'<a href="https://doi.org/{doi}">Published version</a>'
        if body.count(link) != 1:
            raise ValueError(f"doi_labels: expected one 'Published version' link to {doi}, "
                             f"found {body.count(link)}")
        body = body.replace(link, f'<a href="https://doi.org/{doi}">{html.escape(label)}</a>')

    body = paper_pages.link_entries(body, keys, by_key, repos, hidden_repos)
    entries = paper_pages.split_entries(body, keys, by_key)
    counts = paper_pages.write_pages(entries, by_key, abstracts, repos)

    images = LOCAL_IMG_RE.findall(body)
    for rel in images:
        dest = HERE / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(PAPER_IMAGES / Path(rel).name, dest)

    RECENT_DEST.write_text(recent_preprints(body))
    DEST.write_text(header() + '```{=html}\n<div id="pub-list">\n' + body.strip()
                    + "\n</div>\n```\n")
    n = body.count('class="pub filterable')
    no_img = [p["pid"] for p in pubs
              if p["reference_type"] in {"unpublished", "article", "book", "inproceedings",
                                         "techreport", "phdthesis"}
              and not (PAPER_IMAGES / f"{p['pid']}.png").is_file()]
    print(f"Wrote {DEST.name}: {n} publications ({n_preprint} arXiv articles listed as "
          f"preprints), {len(images)} with images, "
          f"{len(no_img)} without")
    print(f"Paper pages in {paper_pages.PAGES_DIR.name}/: {len(entries)} ({counts['new']} new); "
          f"abstracts from .bib {counts['bib']}, from arXiv {counts['arxiv']}, "
          f"from Crossref {counts['crossref']}, "
          f"none {len(counts['none'])}; repositories {counts['repo']}")
    if counts["none"]:
        print("  no abstract: " + " ".join(counts["none"]))


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_BIB)
